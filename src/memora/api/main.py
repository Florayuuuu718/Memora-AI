@app.get("/events")
def events(
    strategy: str = "time_clip_gps",
    people_path: str = "data/people.json",
    generate_names: bool = False,
    use_llm: bool | None = None,
) -> dict:
    valid = {"time_only", "time_clip", "time_clip_gps", "strict_event", "strict_event_people"}
    if strategy not in valid:
        raise HTTPException(status_code=400, detail=f"strategy must be one of: {', '.join(sorted(valid))}")
    if generate_names:
        try:
            inferred_config, _ = infer_journey_config(service.records)
            locations = (inferred_config.home,) + inferred_config.destinations
        except ValueError:
            locations = ()
        backend = _llm_backend(use_llm)
        values = service.named_events(
            strategy=strategy,
            people_path=people_path,
            backend=backend,
            locations=locations,
        )
    else:
        values = service.events(strategy=strategy, people_path=people_path)
    response = {"strategy": strategy, "events": [event.__dict__ for event in values]}
    if generate_names:
        response["narrative_backend"] = _llm_status(backend)
    return response


@app.post("/journeys/discover")
def journeys(request: JourneyDiscoverRequest) -> dict:
    if request.home is None:
        try:
            config, location_clusters = infer_journey_config(
                service.records,
                cluster_radius_km=request.location_cluster_radius_km,
                minimum_destination_photos=request.minimum_destination_photos,
                max_gap_days=request.max_gap_days,
                stop_radius_km=request.stop_radius_km,
            )
        except ValueError as exc:
            raise HTTPException(status_code=400, detail=str(exc)) from exc
        location_mode = "auto_gps"
    else:
        config = JourneyConfig(
            home=NamedLocation(
                request.home.name,
                request.home.latitude,
                request.home.longitude,
                request.home.radius_km,
            ),
            destinations=tuple(
                NamedLocation(value.name, value.latitude, value.longitude, value.radius_km)
                for value in request.destinations
            ),
            max_gap_days=request.max_gap_days,
            stop_radius_km=request.stop_radius_km,
        )
        location_clusters = []
        location_mode = "manual_override"
    backend = _llm_backend(request.use_llm)
    events, values = service.journeys(
        config,
        people_path=request.people_path,
        strategy=request.strategy,
        backend=backend,
    )
    return {
        "config": config.to_dict(),
        "location_mode": location_mode,
        "location_clusters": [cluster.to_dict() for cluster in location_clusters],
        "narrative_backend": _llm_status(backend),
        "event_count": len(events),
        "journeys": [journey.__dict__ for journey in values],
    }


