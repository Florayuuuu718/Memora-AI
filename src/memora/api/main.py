@app.put("/projects/{project_id}/annotations/{kind}/{item_id}")
def update_project_annotation(project_id: str, kind: str, item_id: int, request: ProjectAnnotationRequest) -> dict:
    _project(project_id)
    if kind not in {"people", "events", "journeys"}:
        raise HTTPException(status_code=400, detail="Unsupported annotation kind")
    annotations = projects.load_annotations(project_id)
    current = annotations[kind].get(str(item_id), {})
    name = request.name.strip() if request.name else current.get("name")
    note = request.note.strip() if request.note else current.get("note")
    if request.auto_generate_name and not name:
        name = f"{kind[:-1].title()} {item_id + 1}"
