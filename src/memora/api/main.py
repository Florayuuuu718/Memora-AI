@app.get("/projects/{project_id}/people")
def project_people(project_id: str) -> dict:
    _project(project_id)
    index = load_people_index(projects.people_path(project_id))
    records = {record.id: record for record in _project_service(project_id).records}
    face_counts: dict[str, int] = {}
    for face in index.faces:
        face_counts[face.photo_id] = face_counts.get(face.photo_id, 0) + 1
    annotations = projects.load_annotations(project_id)["people"]
    groups = []
    for group in index.groups:
        candidates = [photo for photo in group.photo_ids if face_counts.get(photo) == 1] or group.photo_ids
        cover = max(candidates, key=lambda photo: records.get(photo).quality.get("score", 0.0) if records.get(photo) else 0.0, default=None)
        item = {**group.__dict__, "cover_photo_id": cover, "cover_url": f"/projects/{project_id}/people/{group.id}/cover", **annotations.get(str(group.id), {})}
        groups.append(item)
    return {"groups": groups, "faces": [face.__dict__ for face in index.faces]}


@app.get("/projects/{project_id}/people/{person_id}/cover")
def project_person_cover(project_id: str, person_id: int):
    cover_id, face, crop_face = _person_cover_data(project_id, person_id)
    path = _project_photo(project_id, cover_id)
    if not crop_face or face is None or len(face.bbox) < 4:
        return FileResponse(path)
    with Image.open(path) as source:
        image = ImageOps.exif_transpose(source).convert("RGB")
        left, top, right, bottom = (float(value) for value in face.bbox[:4])
        face_width, face_height = max(1.0, right - left), max(1.0, bottom - top)
        side = max(face_width, face_height) * 2.2
        center_x, center_y = (left + right) / 2, (top + bottom) / 2
        crop = (
            max(0, int(center_x - side / 2)),
            max(0, int(center_y - side / 2)),
            min(image.width, int(center_x + side / 2)),
            min(image.height, int(center_y + side / 2)),
        )
        portrait = image.crop(crop)
        output = BytesIO()
        portrait.save(output, format="JPEG", quality=90, optimize=True)
        output.seek(0)
    return StreamingResponse(output, media_type="image/jpeg", headers={"Cache-Control": "private, max-age=3600"})


@app.post("/projects/{project_id}/people/cluster")
def cluster_project_people(project_id: str, request: PeopleClusterRequest) -> dict:
    project_service = _project_service(project_id)
    if not project_service.records:
        raise HTTPException(status_code=400, detail="Analyze the project before clustering people")
    try:
        ctx_id = _face_ctx_id(request.ctx_id)
        encoder = InsightFaceEncoder(model_name=request.model_name, ctx_id=ctx_id)
        people_index = cluster_people(
            project_service.records,
            encoder,
            model_name=request.model_name,
            eps=request.eps,
            min_samples=request.min_samples,
        )
        save_people_index(people_index, projects.people_path(project_id))
        _enrich_quality_with_faces(project_service, people_index)
    except (ImportError, RuntimeError, ValueError) as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    records = {record.id: record for record in project_service.records}
    annotations = projects.load_annotations(project_id)["people"]
    face_counts: dict[str, int] = {}
    for face in people_index.faces:
        face_counts[face.photo_id] = face_counts.get(face.photo_id, 0) + 1
    groups = []
    for group in people_index.groups:
        candidates = [photo for photo in group.photo_ids if face_counts.get(photo) == 1] or group.photo_ids
        cover = max(candidates, key=lambda photo: records.get(photo).quality.get("score", 0.0) if records.get(photo) else 0.0, default=None)
        groups.append({
            **group.__dict__,
            "cover_photo_id": cover,
            "cover_url": f"/projects/{project_id}/people/{group.id}/cover",
            **annotations.get(str(group.id), {}),
        })
    return {"groups": groups, "faces": [face.__dict__ for face in people_index.faces], "ctx_id": ctx_id}


