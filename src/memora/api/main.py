@app.get("/projects/{project_id}/export/best-shots.zip")
def export_best_shots_zip(project_id: str, limit: int = 20) -> FileResponse:
    project = _project(project_id)
    records = sorted(
        _project_service(project_id).records,
        key=lambda record: record.quality.get("score", 0.0),
        reverse=True,
    )[: max(1, min(limit, 50))]
    if not records:
        raise HTTPException(status_code=400, detail="Analyze the project before exporting best shots")
    export_dir = projects.directory(project_id) / "exports"
    export_dir.mkdir(parents=True, exist_ok=True)
    archive = export_dir / "best-shots.zip"
    manifest = []
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as output:
        for rank, record in enumerate(records, start=1):
            source = Path(record.path)
            name = f"{rank:02d}-{record.id}-{source.name}"
            output.write(source, arcname=f"photos/{name}")
            manifest.append({
                "rank": rank,
                "photo_id": record.id,
                "filename": source.name,
                "quality": record.quality,
            })
        output.writestr(
            "best-shots.json",
            json.dumps({"project": project.to_dict(), "photos": manifest}, ensure_ascii=False, indent=2),
        )
    filename = re.sub(r"[^A-Za-z0-9_-]+", "-", project.name).strip("-") or project.id
    return FileResponse(archive, filename=f"{filename}-best-shots.zip", media_type="application/zip")


